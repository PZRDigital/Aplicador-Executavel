def _bits( data ):
    return [( data[i // 8] >> ( 7 - i % 8 ) ) & 1 for i in range( len( data ) * 8 )]


def _bytes( bits ):
    out = bytearray( len( bits ) // 8 )
    for i, b in enumerate( bits ):
        if b:
            out[i // 8] |= 0x80 >> ( i % 8 )
    return bytes( out )


def _block( b ):
    bits = _bits( b )
    x = [bits[i - 1] for i in IP]
    left, right = x[:32], x[32:]
    e = [right[i - 1] for i in E]
    s = []
    for k in range( 8 ):
        six = e[k * 6:k * 6 + 6]
        row = ( six[0] << 1 ) | six[5]
        col = ( six[1] << 3 ) | ( six[2] << 2 ) | ( six[3] << 1 ) | six[4]
        v = SBOX[k][row * 16 + col]
        s += [( v >> 3 ) & 1, ( v >> 2 ) & 1, ( v >> 1 ) & 1, v & 1]
    f = [s[i - 1] for i in P]
    left = [a ^ c for a, c in zip( left, f )]
    y = left + right
    return _bytes( [y[i - 1] for i in FP] )


_CACHE = {}


def _decrypt_block( b ):
    r = _CACHE.get( b )
    if r is None:
        r = _CACHE[b] = _block( b )
    return r


SUBST = {0x00: 0x2B, 0x2B: 0x00, 0x6C: 0x80, 0x01: 0x68, 0x68: 0x01, 0x48: 0x77, 0x60: 0xFF, 0x77: 0x48,
         0xB9: 0xC0, 0xC0: 0xB9, 0xFE: 0xEB, 0xEB: 0xFE, 0x80: 0x6C, 0xFF: 0x60}


def _shuffle( b ):
    return bytes( [b[3], b[4], b[6], b[0], b[1], b[2], b[5], SUBST.get( b[7], b[7] )] )


def decode( data, flags, comp_len ):
    """data = bytes alinhados em 8 (tamanho alinhado da entrada); comp_len = tamanho comprimido real."""
    out = bytearray( data )
    n = len( out ) // 8
    if flags & 2:
        digits = len( str( comp_len ) )
        cycle = 1 if digits < 3 else digits + 1 if digits < 5 else digits + 9 if digits < 7 else digits + 15
        j = -1
        for i in range( n ):
            blk = bytes( out[i * 8:i * 8 + 8] )
            if i < 20 or i % cycle == 0:
                out[i * 8:i * 8 + 8] = _decrypt_block( blk )
                continue
            j += 1
            if j % 7 == 0 and j != 0:
                out[i * 8:i * 8 + 8] = _shuffle( blk )
    elif flags & 4:
        for i in range( min( 20, n ) ):
            out[i * 8:i * 8 + 8] = _decrypt_block( bytes( out[i * 8:i * 8 + 8] ) )
    return bytes( out )
